#!/usr/bin/env node
// Bake step: turns customers + CSAV associations into a model.json.
//   node bake.mjs customers.json avs.json [out.json] [--gates]
//
// Default (keys mode, recommended): the hierarchy is NOT in the model.
//   One hidden key item per customer that some AV is tied to. An API returns [id, parent, grandparent] when the user picks a customer,
//   and the UI selects the key items for those ids. Each AV has an OR gate fed by its customers' key items.
// --gates mode: the hierarchy IS in the model. Every customer is an item with a gate that feeds its parent's gate,
//   so choosing an org turns on the org, account and top gates. Each AV gate is fed by the gate of the customer it is tied to.
// In both modes an AV tied to no customer has no gate and is always available.
import fs from "fs";

const item = (partno, partdes, precon, extra = {}) => ({ partno, partdes, visible: true, precon, selcon: false, selected: false, inode: 0, ...extra });
const choice = (chaId, chaDes, multiple, precon, firstItem, lastItem) => ({ chaId, chaDes, multiple, required: false, visible: true, precon, selcon: false, firstItem, lastItem });

function validate(customers, avs) {
  const byId = new Map(customers.map(c => [c.id, c]));
  if (byId.size !== customers.length) throw new Error("duplicate customer id");
  for (const c of customers) {
    if (c.parent && !byId.has(c.parent)) throw new Error(`customer ${c.id}: unknown parent ${c.parent}`);
    for (let p = c, n = 0; p.parent; p = byId.get(p.parent)) if (++n > customers.length) throw new Error(`cycle in the hierarchy at ${c.id}`);
  }
  for (const a of avs) for (const id of a.customers || []) if (!byId.has(id)) throw new Error(`AV ${a.partno}: unknown customer ${id}`);
  return byId;
}

function builder() {
  const nodes = [];
  const add = (name, edges = []) => { const n = { id: nodes.length, name, type: 2, g: -1, a: 0, b: 0, edges }; nodes.push(n); return n; };
  const finish = () => { for (const n of nodes) {                       // merge edges of the same type into one
    const m = new Map(); for (const e of n.edges) m.set(e.type, [...(m.get(e.type) || []), ...e.node]);
    n.edges = [...m].map(([type, node]) => ({ type, node })); } return nodes; };
  return { nodes, add, finish };
}
const I_AVL = 0x43, GTE_0 = 2;

// AV gates: P_Item_x (g = -1) -> I_AVL on the AV item; returns the gate for each AV that is tied to customers
function avGates(b, avs, firstAvItem) {
  const gates = new Map();
  avs.forEach((a, j) => { if ((a.customers || []).length) gates.set(a.partno, b.add(`P_Item_${a.partno} (OR over ${a.customers.length} customer${a.customers.length > 1 ? "s" : ""})`, [{ type: I_AVL, node: [firstAvItem + j] }])); });
  return gates;
}
const avItems = avs => avs.map(a => item(a.partno, a.desc, (a.customers || []).length ? -1 : 0));

export function bakeKeys(customers, avs) {
  const byId = validate(customers, avs);
  const tied = [...new Set(avs.flatMap(a => a.customers || []))];
  const items = [...tied.map(id => item("KEY:" + id, "Customer key " + byId.get(id).name, 0, { mdmId: byId.get(id).mdmId })), ...avItems(avs)];
  const b = builder();
  items.forEach((it, i) => { b.add(i < tied.length ? it.partno : "Item_" + it.partno); it.inode = i; });
  const gates = avGates(b, avs, tied.length);
  for (const a of avs) for (const id of a.customers || []) b.nodes[tied.indexOf(id)].edges.push({ type: GTE_0, node: [gates.get(a.partno).id] });
  return { _comment: "GENERATED by bake.mjs (keys mode).", Chaids: [choice("CUSTKEY", "Customer keys (hidden, set from the API result)", true, 0, 0, Math.max(tied.length - 1, 0)), choice("SERVICES", "Services AVs", true, 0, tied.length, items.length - 1)], Items: items, Nodes: b.finish() };
}

export function bakeGates(customers, avs) {
  const byId = validate(customers, avs), n = customers.length;
  const items = [...customers.map(c => item("CUST:" + c.id, `L${c.level} ${c.name}`, 0, { mdmId: c.mdmId })), ...avItems(avs)];
  const b = builder();
  items.forEach((it, i) => { b.add(i < n ? it.partno : "Item_" + it.partno); it.inode = i; });
  const gate = new Map(customers.map(c => [c.id, b.add(`G_${c.id} (L${c.level}: ${c.name} or anything below it chosen)`)]));
  customers.forEach((c, i) => {
    b.nodes[i].edges.push({ type: GTE_0, node: [gate.get(c.id).id] });                   // customer item -> own gate
    if (c.parent) gate.get(c.id).edges.push({ type: GTE_0, node: [gate.get(c.parent).id] });   // gate -> parent gate
  });
  const gates = avGates(b, avs, n);
  for (const a of avs) for (const id of a.customers || []) gate.get(id).edges.push({ type: GTE_0, node: [gates.get(a.partno).id] });
  return { _comment: "GENERATED by bake.mjs (--gates mode).", Chaids: [choice("CUST", "Customer (any level)", false, 0, 0, n - 1), choice("SERVICES", "Services AVs", true, 0, n, items.length - 1)], Items: items, Nodes: b.finish() };
}

export function writeModel(model, out) {
  const line = o => "    " + JSON.stringify(o);
  fs.writeFileSync(out, `{\n  "_comment": ${JSON.stringify(model._comment)},\n  "Chaids": [\n${model.Chaids.map(line).join(",\n")}\n  ],\n  "Items": [\n${model.Items.map(line).join(",\n")}\n  ],\n  "Nodes": [\n${model.Nodes.map(line).join(",\n")}\n  ]\n}\n`);
}

if (process.argv[1]?.endsWith("bake.mjs")) {
  const gates = process.argv.includes("--gates");
  const [cf = "customers.json", af = "avs.json", out = gates ? "model.gates.json" : "model.keys.json"] = process.argv.slice(2).filter(a => !a.startsWith("--"));
  const model = (gates ? bakeGates : bakeKeys)(JSON.parse(fs.readFileSync(cf, "utf8")), JSON.parse(fs.readFileSync(af, "utf8")));
  writeModel(model, out);
  console.log(`${out}: ${model.Items.length} items, ${model.Nodes.length} nodes, ${model.Nodes.reduce((s, n) => s + n.edges.reduce((t, e) => t + e.node.length, 0), 0)} wires`);
}
